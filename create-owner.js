import 'dotenv/config';
import bcrypt from 'bcryptjs';
import {db} from './db.js';
const {OWNER_EMAIL,OWNER_PASSWORD}=process.env;
if(!OWNER_EMAIL || !OWNER_PASSWORD || OWNER_PASSWORD.length<12)throw new Error('Set OWNER_EMAIL and OWNER_PASSWORD (12+ chars) in .env');
const hash=await bcrypt.hash(OWNER_PASSWORD,12);
const [rows]=await db.query("SELECT COUNT(*) AS count FROM admins WHERE role='owner'");
if(rows[0].count>0)throw new Error('Owner already exists; refusing to create another');
await db.execute('INSERT INTO admins(email,password_hash,role) VALUES(?,?,?)',[OWNER_EMAIL.toLowerCase(),hash,'owner']);
console.log('Owner created');await db.end();
